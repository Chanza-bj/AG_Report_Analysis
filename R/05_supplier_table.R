# =============================================================================
# 05_supplier_table.R  -  Build the data for the dashboard's searchable supplier
# table: the full index of named companies, enriched with a delivery status
# (Delivered / Partial / Not delivered) and an amount WHERE THAT IS KNOWN
# (from the valued contracts and the 2022 seed table). Most names have no
# delivery detail - they are appearances only, shown with status "".
#
# Output: site/suppliers_data.js  ->  const SUPPLIERS = [...]
# =============================================================================
suppressMessages({library(readr);library(dplyr);library(stringr);library(purrr);library(jsonlite)})

idx   <- read_csv("data_clean/supplier_index.csv",   show_col_types = FALSE) |>
  filter(verified_in_text)
seed  <- read_csv("data_clean/seed_delivery_2022.csv", show_col_types = FALSE)
contr <- read_csv("data_clean/contracts_flagged.csv",  show_col_types = FALSE)

nk <- function(x) x |> str_to_lower() |>
  str_replace_all("\\b(limited|ltd|ltd\\.|co\\.|co|company|incorporated|inc|plc|pte|pty)\\b"," ") |>
  str_replace_all("[^a-z0-9 ]"," ") |> str_squish()

# Known delivery/amount from the seed table (2022)
seed_known <- seed |> transmute(key = nk(supplier), name = supplier,
  status = case_when(pct_undelivered_reported >= 100 ~ "Not delivered",
                     pct_undelivered_reported <= 0   ~ "Delivered",
                     TRUE ~ "Partial"),
  amount = contract_sum_zmw, cur = "ZMW", ay = 2022L)

# Known delivery/amount from the valued contracts
contr_known <- contr |>
  filter(!str_detect(supplier, "seed suppliers")) |>
  transmute(key = nk(supplier), name = supplier,
    status = recode(delivered, Yes="Delivered", No="Not delivered", Partial="Partial", .default=""),
    amount = coalesce(contract_value, amount_at_issue),
    cur = coalesce(contract_currency, amount_currency), ay = financial_year)

known <- bind_rows(seed_known, contr_known) |>
  group_by(key) |> slice(1) |> ungroup()        # one status per supplier

# Base: every verified index supplier
base <- idx |> transmute(key = nk(supplier), name = supplier,
  years = years_appearing, mentions = total_mentions)

# Add any known-contract suppliers not already in the index (real flagged firms)
extra <- known |> filter(!key %in% base$key) |>
  transmute(key, name, years = as.character(ay), mentions = 1L)

all <- bind_rows(base, extra) |>
  left_join(known |> select(key, status, amount, cur, ay), by = "key") |>
  mutate(status = coalesce(status, ""),
         years = str_replace_all(years, ";", ", ")) |>
  arrange(desc(nchar(status)>0), years, name) |>
  transmute(n = name, y = years, m = mentions,
            s = status, a = ifelse(is.na(amount), NA, amount),
            c = ifelse(is.na(cur), "", cur), ay = ifelse(is.na(ay), NA, ay))

js <- paste0("/* generated by R/05_supplier_table.R - do not edit by hand */\n",
             "const SUPPLIERS = ", toJSON(all, dataframe="rows", na="null", auto_unbox=TRUE), ";\n")
writeLines(js, "site/suppliers_data.js")

cat("suppliers written:", nrow(all), "\n")
cat("with known delivery status:", sum(all$s != ""), "\n")
cat("status counts:\n"); print(table(all$s[all$s!=""]))
