# =============================================================================
# 13_case_stories.R  -  Case stories for readers who will not read the reports.
# Each story in data_clean/case_stories.csv was read on its PDF page(s) before
# being written up. This script writes:
#   site/stories_data.js           const STORIES (rendered as cards on the dashboard)
#   site/stories/<id>.html          one share page per story, with its own
#                                   Open Graph title/description so a WhatsApp or
#                                   LinkedIn link previews that story, then sends
#                                   the reader to the story on the dashboard.
# =============================================================================
suppressMessages({library(readr); library(dplyr); library(jsonlite)})

BASE <- "https://chanza-bj.github.io/AG_Report_Analysis"
s <- read_csv("data_clean/case_stories.csv", show_col_types = FALSE,
              col_types = cols(.default = col_character()))

esc <- function(x) x |> gsub("&", "&amp;", x = _, fixed = TRUE) |>
  gsub("<", "&lt;", x = _, fixed = TRUE) |> gsub(">", "&gt;", x = _, fixed = TRUE) |>
  gsub("\"", "&quot;", x = _, fixed = TRUE)

cite <- function(y, p) sprintf("Auditor General, %s report, PDF page%s %s",
                               y, ifelse(grepl("-", p), "s", ""), p)

js <- paste0("/* generated by R/13_case_stories.R - do not edit by hand */\n",
             "const STORIES = ",
             toJSON(s |> mutate(cite = cite(report_year, pdf_pages),
                                share = sprintf("%s/stories/%s.html", BASE, id)),
                    dataframe = "rows", auto_unbox = TRUE), ";\n")
writeLines(js, "site/stories_data.js")

dir.create("site/stories", showWarnings = FALSE)
for (i in seq_len(nrow(s))) {
  r <- s[i, ]
  url  <- sprintf("%s/stories/%s.html", BASE, r$id)
  dest <- sprintf("../index.html#story-%s", r$id)
  desc <- sprintf("%s %s Source: %s.", r$paid, r$outcome, cite(r$report_year, r$pdf_pages))
  html <- c(
    "<!doctype html>", "<html lang=\"en\"><head>", "<meta charset=\"utf-8\">",
    "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">",
    sprintf("<title>%s</title>", esc(r$headline)),
    sprintf("<meta name=\"description\" content=\"%s\">", esc(desc)),
    "<meta property=\"og:type\" content=\"article\">",
    "<meta property=\"og:site_name\" content=\"Zambia Public Finance &amp; Audit Dashboard\">",
    sprintf("<meta property=\"og:title\" content=\"%s\">", esc(r$headline)),
    sprintf("<meta property=\"og:description\" content=\"%s\">", esc(desc)),
    sprintf("<meta property=\"og:url\" content=\"%s\">", url),
    "<meta name=\"twitter:card\" content=\"summary\">",
    sprintf("<link rel=\"canonical\" href=\"%s\">", url),
    sprintf("<meta http-equiv=\"refresh\" content=\"0; url=%s\">", dest),
    "<style>body{font:16px/1.6 system-ui,sans-serif;max-width:640px;margin:40px auto;padding:0 16px;color:#10151b;background:#fff}a{color:#1c5cab}small{color:#5b6470}</style>",
    "</head><body>",
    sprintf("<h1 style=\"font-size:22px\">%s</h1>", esc(r$headline)),
    sprintf("<p>%s</p><p>%s</p><p>%s</p>", esc(r$summary), esc(r$paid), esc(r$outcome)),
    sprintf("<p><small>%s. Position as at %s; later delivery or recovery may not be reflected. An audit finding is a question, not proof of wrongdoing.</small></p>",
            esc(cite(r$report_year, r$pdf_pages)), esc(r$as_at)),
    sprintf("<p><a href=\"%s\">Open this story on the dashboard</a></p>", dest),
    "</body></html>")
  writeLines(html, sprintf("site/stories/%s.html", r$id), useBytes = TRUE)
}
cat("stories:", nrow(s), "| share pages written to site/stories/\n")
