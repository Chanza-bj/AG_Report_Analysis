# =============================================================================
# 08_cases_data.R  -  Supplier cases: goods & services flagged across the
# reports (suppliers, items, amounts, delivery status, page). From the
# user-supplied extraction (data_raw/supplier_cases_raw.csv), spot-verified
# against pages (Pembe Milling p95, Ranch Agro Tech p215).
# Output: data_clean/supplier_cases.csv  and  site/cases_data.js (const CASES)
# =============================================================================
suppressMessages({library(readr); library(dplyr); library(stringr); library(jsonlite)})

d <- read_csv("data_raw/supplier_cases_raw.csv", show_col_types = FALSE) |>
  mutate(across(everything(), ~str_squish(as.character(.)))) |>
  mutate(named = !str_detect(supplier, regex("not named|not named in extract", ignore_case = TRUE)),
         not_delivered = str_detect(delivered, regex("none|not delivered|not received|nil|^0 |0 MT|0 bags|0 heifers|0 delivered", ignore_case = TRUE)))

write_csv(d, "data_clean/supplier_cases.csv")

cases <- d |> transmute(
  y = report_year, e = entity, s = supplier, it = item,
  cv = contract_value, ap = amount_paid, uv = undelivered_value,
  d = delivered, st = status_as_at, p = pdf_page,
  named = named, nd = not_delivered)

js <- paste0("/* generated by R/08_cases_data.R - supplier cases (goods & services) */\n",
             "const CASES = ", toJSON(cases, dataframe = "rows", na = "string", auto_unbox = TRUE), ";\n")
writeLines(js, "site/cases_data.js")

cat("cases:", nrow(d), "| named suppliers:", sum(d$named),
    "| not delivered:", sum(d$not_delivered), "\n")
cat("by year:\n"); print(table(d$report_year))
