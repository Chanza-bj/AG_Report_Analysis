# Generate site/valued_data.js (const VALUED) from the full ~182 valued-contract
# list, for the searchable "all valued contracts" table.
suppressMessages({library(readr); library(dplyr); library(stringr); library(jsonlite)})

d <- read_csv("data_raw/contracts_valued_all.csv", show_col_types = FALSE)

# Mark which valued rows are already deep-verified (match contracts_flagged by
# year + page + amount, where the amount appears as contract value or at-issue).
cf <- read_csv("data_clean/contracts_flagged.csv", show_col_types = FALSE) |>
  mutate(cv = suppressWarnings(as.numeric(contract_value)),
         ai = suppressWarnings(as.numeric(amount_at_issue)),
         yr = financial_year, pg = source_pdf_page)
is_verified <- function(y, pg, amt) {
  m <- cf[cf$yr == y & cf$pg == pg, ]
  if (!nrow(m)) return(FALSE)
  any(abs(m$cv - amt) < 1, na.rm = TRUE) || any(abs(m$ai - amt) < 1, na.rm = TRUE) ||
    # same page & only one flagged contract there -> treat as verified
    nrow(m) == 1
}
d$verified <- mapply(is_verified, d$financial_year, d$pdf_page, d$amount)

fmt <- function(a, c) ifelse(c == "US$",
         ifelse(a >= 1e6, paste0("US$", round(a/1e6, 1), "m"), paste0("US$", format(round(a), big.mark=","))),
       ifelse(c == "N$", paste0("N$", format(round(a), big.mark=",")),
         ifelse(a >= 1e9, paste0("K", round(a/1e9, 2), "bn"),
         ifelse(a >= 1e6, paste0("K", round(a/1e6, 1), "m"), paste0("K", format(round(a), big.mark=","))))))

v <- d |>
  mutate(ministry_short = str_replace(ministry, "Ministry of ", "") |>
           str_replace("Office of the President - ", "OP ") |> str_trunc(34),
         amt = fmt(amount, currency)) |>
  transmute(y = financial_year, m = ministry_short, cur = currency,
            amt = amt, p = pdf_page, ctx = str_squish(context), v = verified)

js <- paste0("/* generated by R/09_valued_data.R - all ~182 valued contracts */\n",
             "const VALUED = ", toJSON(v, dataframe = "rows", na = "string", auto_unbox = TRUE), ";\n")
writeLines(js, "site/valued_data.js")
cat("valued contracts:", nrow(v), "| by year:\n"); print(table(v$y))
